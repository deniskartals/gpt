"""Reading and writing OBJ, STL (ASCII/binary) and PLY (ASCII/binary) files."""

from __future__ import annotations

import os
import re
import struct
from typing import Callable, Dict, List, Tuple, Union

from .mesh import Mesh
from .vector import Vec3

PathLike = Union[str, os.PathLike]


def _stem(path: PathLike) -> str:
    return os.path.splitext(os.path.basename(os.fspath(path)))[0] or "mesh"


# ---------------------------------------------------------------------------
# OBJ
# ---------------------------------------------------------------------------
def save_obj(mesh: Mesh, path: PathLike, normals: bool = False) -> None:
    """Write a Wavefront OBJ file, optionally with smooth vertex normals."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("# generated by model3d\n")
        f.write(f"o {mesh.name}\n")
        for p in mesh.vertices:
            f.write(f"v {p.x:.9g} {p.y:.9g} {p.z:.9g}\n")
        if normals:
            for n in mesh.vertex_normals():
                f.write(f"vn {n.x:.9g} {n.y:.9g} {n.z:.9g}\n")
            for a, b, c in mesh.faces:
                f.write(f"f {a + 1}//{a + 1} {b + 1}//{b + 1} {c + 1}//{c + 1}\n")
        else:
            for a, b, c in mesh.faces:
                f.write(f"f {a + 1} {b + 1} {c + 1}\n")


def load_obj(path: PathLike) -> Mesh:
    """Read vertices and faces from an OBJ file (all objects are merged)."""
    vertices: List[Vec3] = []
    faces: List[List[int]] = []
    name = _stem(path)
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for lineno, line in enumerate(f, 1):
            parts = line.split("#", 1)[0].split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "v":
                if len(parts) < 4:
                    raise ValueError(f"{path}:{lineno}: vertex needs 3 coordinates")
                vertices.append(Vec3(float(parts[1]), float(parts[2]), float(parts[3])))
            elif tag == "f":
                face = []
                for token in parts[1:]:
                    i = int(token.split("/", 1)[0])
                    # OBJ indices are 1-based; negative indices are relative.
                    face.append(i - 1 if i > 0 else len(vertices) + i)
                faces.append(face)
            elif tag == "o" and len(parts) > 1:
                name = " ".join(parts[1:])
    return Mesh(vertices, faces, name=name)


# ---------------------------------------------------------------------------
# STL
# ---------------------------------------------------------------------------
def save_stl(mesh: Mesh, path: PathLike, binary: bool = True) -> None:
    """Write an STL file (binary by default)."""
    normals = mesh.face_normals()
    if binary:
        with open(path, "wb") as f:
            header = f"model3d {mesh.name}".encode("ascii", "replace")[:80]
            f.write(header.ljust(80, b" "))
            f.write(struct.pack("<I", len(mesh.faces)))
            for n, (a, b, c) in zip(normals, mesh.triangles()):
                f.write(struct.pack("<12fH", *n, *a, *b, *c, 0))
    else:
        with open(path, "w", encoding="ascii") as f:
            f.write(f"solid {mesh.name}\n")
            for n, tri in zip(normals, mesh.triangles()):
                f.write(f"  facet normal {n.x:.9g} {n.y:.9g} {n.z:.9g}\n    outer loop\n")
                for p in tri:
                    f.write(f"      vertex {p.x:.9g} {p.y:.9g} {p.z:.9g}\n")
                f.write("    endloop\n  endfacet\n")
            f.write(f"endsolid {mesh.name}\n")


_STL_VERTEX = re.compile(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)")


def load_stl(path: PathLike, weld: bool = True) -> Mesh:
    """Read an ASCII or binary STL file.

    STL stores every triangle separately, so by default coincident vertices
    are welded to recover a connected mesh.
    """
    with open(path, "rb") as f:
        data = f.read()
    name = _stem(path)
    vertices: List[Tuple[float, float, float]] = []
    is_binary = len(data) >= 84 and 84 + 50 * struct.unpack_from("<I", data, 80)[0] == len(data)
    if is_binary:
        count = struct.unpack_from("<I", data, 80)[0]
        for k in range(count):
            vals = struct.unpack_from("<12f", data, 84 + 50 * k)
            vertices += [vals[3:6], vals[6:9], vals[9:12]]
    elif data.lstrip().startswith(b"solid"):
        first = data.lstrip().split(b"\n", 1)[0].split(None, 1)
        if len(first) > 1 and first[1].strip():
            name = first[1].strip().decode("ascii", "replace")
        for m in _STL_VERTEX.finditer(data):
            vertices.append(tuple(float(v) for v in m.groups()))
        if len(vertices) % 3:
            raise ValueError(f"{path}: vertex count is not a multiple of 3")
    else:
        raise ValueError(f"{path}: not a valid STL file")
    faces = [(i, i + 1, i + 2) for i in range(0, len(vertices), 3)]
    mesh = Mesh(vertices, faces, name=name)
    return mesh.welded(1e-6) if weld else mesh


# ---------------------------------------------------------------------------
# PLY
# ---------------------------------------------------------------------------
_PLY_TYPES: Dict[str, str] = {
    "char": "b", "int8": "b", "uchar": "B", "uint8": "B",
    "short": "h", "int16": "h", "ushort": "H", "uint16": "H",
    "int": "i", "int32": "i", "uint": "I", "uint32": "I",
    "float": "f", "float32": "f", "double": "d", "float64": "d",
}


def save_ply(mesh: Mesh, path: PathLike, binary: bool = False) -> None:
    """Write a PLY file (ASCII by default, binary little-endian if requested)."""
    fmt = "binary_little_endian" if binary else "ascii"
    header = (
        f"ply\nformat {fmt} 1.0\ncomment generated by model3d\n"
        f"comment name {mesh.name}\n"
        f"element vertex {len(mesh.vertices)}\n"
        "property float x\nproperty float y\nproperty float z\n"
        f"element face {len(mesh.faces)}\n"
        "property list uchar int vertex_indices\nend_header\n"
    )
    with open(path, "wb") as f:
        f.write(header.encode("ascii"))
        if binary:
            for p in mesh.vertices:
                f.write(struct.pack("<3f", p.x, p.y, p.z))
            for face in mesh.faces:
                f.write(struct.pack("<B3i", 3, *face))
        else:
            lines = [f"{p.x:.9g} {p.y:.9g} {p.z:.9g}" for p in mesh.vertices]
            lines += [f"3 {a} {b} {c}" for a, b, c in mesh.faces]
            f.write(("\n".join(lines) + "\n").encode("ascii"))


def load_ply(path: PathLike) -> Mesh:
    """Read vertex positions and faces from an ASCII or binary PLY file."""
    with open(path, "rb") as f:
        data = f.read()
    end = re.search(rb"end_header\r?\n", data)
    if not data.startswith(b"ply") or end is None:
        raise ValueError(f"{path}: not a valid PLY file")
    header = data[: end.start()].decode("ascii", "replace").splitlines()
    body = data[end.end():]

    fmt = None
    name = _stem(path)
    # Each element: (name, count, [(prop_name, type, list_count_type or None)])
    elements: List[Tuple[str, int, List[Tuple[str, str, Union[str, None]]]]] = []
    for line in header[1:]:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "format":
            fmt = parts[1]
        elif parts[0] == "comment" and len(parts) > 2 and parts[1] == "name":
            name = " ".join(parts[2:])
        elif parts[0] == "element":
            elements.append((parts[1], int(parts[2]), []))
        elif parts[0] == "property":
            if parts[1] == "list":
                elements[-1][2].append((parts[4], parts[3], parts[2]))
            else:
                elements[-1][2].append((parts[2], parts[1], None))
    if fmt not in ("ascii", "binary_little_endian", "binary_big_endian"):
        raise ValueError(f"{path}: unsupported PLY format {fmt!r}")

    read_scalar: Callable[[str], float]
    if fmt == "ascii":
        tokens = iter(body.split())

        def read_scalar(type_name: str):
            token = next(tokens)
            return float(token) if _PLY_TYPES[type_name] in "fd" else int(token)
    else:
        endian = "<" if fmt == "binary_little_endian" else ">"
        offset = 0

        def read_scalar(type_name: str):
            nonlocal offset
            code = endian + _PLY_TYPES[type_name]
            (value,) = struct.unpack_from(code, body, offset)
            offset += struct.calcsize(code)
            return value

    vertices: List[Vec3] = []
    faces: List[List[int]] = []
    for elem_name, count, props in elements:
        for _ in range(count):
            record = {}
            for prop_name, type_name, list_type in props:
                if list_type is None:
                    record[prop_name] = read_scalar(type_name)
                else:
                    n = int(read_scalar(list_type))
                    record[prop_name] = [int(read_scalar(type_name)) for _ in range(n)]
            if elem_name == "vertex":
                vertices.append(Vec3(record["x"], record["y"], record["z"]))
            elif elem_name == "face":
                indices = record.get("vertex_indices", record.get("vertex_index"))
                if indices is None:
                    raise ValueError(f"{path}: face element has no vertex index list")
                faces.append(indices)
    return Mesh(vertices, faces, name=name)


# ---------------------------------------------------------------------------
# Dispatch by extension
# ---------------------------------------------------------------------------
_LOADERS = {".obj": load_obj, ".stl": load_stl, ".ply": load_ply}
_SAVERS = {".obj": save_obj, ".stl": save_stl, ".ply": save_ply}


def _ext(path: PathLike) -> str:
    return os.path.splitext(os.fspath(path))[1].lower()


def load(path: PathLike) -> Mesh:
    """Load a mesh, choosing the format from the file extension."""
    loader = _LOADERS.get(_ext(path))
    if loader is None:
        raise ValueError(f"unsupported file type: {path} (supported: {', '.join(_LOADERS)})")
    return loader(path)


def save(mesh: Mesh, path: PathLike, **options) -> None:
    """Save a mesh, choosing the format from the file extension."""
    saver = _SAVERS.get(_ext(path))
    if saver is None:
        raise ValueError(f"unsupported file type: {path} (supported: {', '.join(_SAVERS)})")
    saver(mesh, path, **options)
